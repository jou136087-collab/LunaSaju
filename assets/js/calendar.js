  function vsopSum(terms, tau) {
    var s = 0;
    for (var i = 0; i < terms.length; i++) {
      s += terms[i][0] * Math.cos(terms[i][1] + terms[i][2] * tau);
    }
    return s;
  }

  function vsopSeries(sets, tau) {
    var total = 0;
    for (var i = sets.length - 1; i >= 0; i--) {
      total = total * tau + vsopSum(sets[i], tau);
    }
    return total / 1e8;
  }

  function apparentSolarLongitudeTT(jdTT) {
    var T = (jdTT - 2451545.0) / 36525;
    var tau = T / 10; // 율리우스 천년

    // 지구의 일심 황경 (라디안) -> 태양의 지심 황경 (도)
    var Learth = vsopSeries([VSOP_L0, VSOP_L1, VSOP_L2, VSOP_L3, VSOP_L4, VSOP_L5], tau);
    var R = vsopSeries([VSOP_R0, VSOP_R1, VSOP_R2, VSOP_R3, VSOP_R4], tau);
    var theta = mod360(Learth / RAD + 180);

    // VSOP87(동역학 기준계) -> FK5 보정. 황경 항은 상수 -0.09033"
    theta += -0.09033 / 3600;

    // 장동 (Meeus 22, 주요 4항, 정확도 0.5")
    var Omega = 125.04452 - 1934.136261 * T + 0.0020708 * T * T;
    var Lsun  = 280.4665 + 36000.7698 * T;
    var Lmoon = 218.3165 + 481267.8813 * T;
    var dPsi = (-17.20 * Math.sin(Omega * RAD)
                - 1.32 * Math.sin(2 * Lsun * RAD)
                - 0.23 * Math.sin(2 * Lmoon * RAD)
                + 0.21 * Math.sin(2 * Omega * RAD)) / 3600;

    // 광행차
    var aberration = -20.4898 / (3600 * R);

    return mod360(theta + dPsi + aberration);
  }

  // UT 기준 JD 를 받아 겉보기 황경 반환
  function solarLongitude(jdUT) {
    var approxYear = 2000 + (jdUT - 2451545.0) / 365.25;
    var dt = deltaT(approxYear) / 86400;
    return apparentSolarLongitudeTT(jdUT + dt);
  }

  /* ---------------------------------------------------------------------
   * 절기 시각 찾기 — 목표 황경에 도달하는 UT 기준 JD
   * jdSeed 근처에서 뉴턴법으로 수렴.
   * ------------------------------------------------------------------- */
  function findSolarTermJD(jdSeed, targetLon) {
    var jd = jdSeed;
    for (var i = 0; i < 30; i++) {
      var cur = solarLongitude(jd);
      var diff = mod(targetLon - cur + 180, 360) - 180; // -180 ~ +180
      jd += diff / 0.9856473;
      if (Math.abs(diff) < 1e-8) break;
    }
    return jd;
  }


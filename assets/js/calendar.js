  // 그레고리력 (y, m, d) 0시 UT 기준의 율리우스일. d 는 소수 허용.
  function toJD(y, m, d) {
    if (m <= 2) { y -= 1; m += 12; }
    var A = Math.floor(y / 100);
    var B = 2 - A + Math.floor(A / 4);
    return Math.floor(365.25 * (y + 4716)) +
           Math.floor(30.6001 * (m + 1)) + d + B - 1524.5;
  }

  // 정수 율리우스일(민일 번호). 60갑자 일주 계산에 사용.
  function toJDN(y, m, d) {
    return Math.floor(toJD(y, m, d) + 0.5);
  }

  // JD -> {y, m, d, hour, minute, second}
  function fromJD(jd) {
    var z = Math.floor(jd + 0.5);
    var f = (jd + 0.5) - z;
    var A = z;
    if (z >= 2299161) {
      var alpha = Math.floor((z - 1867216.25) / 36524.25);
      A = z + 1 + alpha - Math.floor(alpha / 4);
    }
    var B = A + 1524;
    var C = Math.floor((B - 122.1) / 365.25);
    var D = Math.floor(365.25 * C);
    var E = Math.floor((B - D) / 30.6001);

    var dayF = B - D - Math.floor(30.6001 * E) + f;
    var day = Math.floor(dayF);
    var month = (E < 14) ? E - 1 : E - 13;
    var year = (month > 2) ? C - 4716 : C - 4715;

    var frac = dayF - day;
    var totalSec = Math.round(frac * 86400);
    var hour = Math.floor(totalSec / 3600);
    var minute = Math.floor((totalSec % 3600) / 60);
    var second = totalSec % 60;
    if (hour >= 24) { hour -= 24; day += 1; } // 반올림 경계 보호

    return { y: year, m: month, d: day, hour: hour, minute: minute, second: second };
  }

  /* ---------------------------------------------------------------------
   * ΔT (TT - UT), 초 단위. Espenak & Meeus 다항식.
   * ------------------------------------------------------------------- */
  function deltaT(decimalYear) {
    var y = decimalYear, t, u;
    if (y < 1900) {
      t = y - 1860;
      return 7.62 + 0.5737 * t - 0.251754 * t * t + 0.01680668 * Math.pow(t, 3) -
             0.0004473624 * Math.pow(t, 4) + Math.pow(t, 5) / 233174;
    }
    if (y < 1920) {
      t = y - 1900;
      return -2.79 + 1.494119 * t - 0.0598939 * t * t +
             0.0061966 * Math.pow(t, 3) - 0.000197 * Math.pow(t, 4);
    }
    if (y < 1941) {
      t = y - 1920;
      return 21.20 + 0.84493 * t - 0.076100 * t * t + 0.0020936 * Math.pow(t, 3);
    }
    if (y < 1961) {
      t = y - 1950;
      return 29.07 + 0.407 * t - t * t / 233 + Math.pow(t, 3) / 2547;
    }
    if (y < 1986) {
      t = y - 1975;
      return 45.45 + 1.067 * t - t * t / 260 - Math.pow(t, 3) / 718;
    }
    if (y < 2005) {
      t = y - 2000;
      return 63.86 + 0.3345 * t - 0.060374 * t * t + 0.0017275 * Math.pow(t, 3) +
             0.000651814 * Math.pow(t, 4) + 0.00002373599 * Math.pow(t, 5);
    }
    if (y < 2050) {
      t = y - 2000;
      return 62.92 + 0.32217 * t + 0.005589 * t * t;
    }
    if (y < 2150) {
      u = (y - 1820) / 100;
      return -20 + 32 * u * u - 0.5628 * (2150 - y);
    }
    u = (y - 1820) / 100;
    return -20 + 32 * u * u;
  }


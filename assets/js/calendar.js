  /* 어떤 순간이 속한 절기 구간의 시작 절입 시각 / 다음 절입 시각 (UT JD) */
  function surroundingTerms(jdUT) {
    var idx = termIndexFromLongitude(solarLongitude(jdUT));
    var startLon = MAJOR_TERMS[idx].lon;
    var nextLon = MAJOR_TERMS[(idx + 1) % 12].lon;

    // 구간 시작: 현재 시각보다 앞에 있는 가장 가까운 해당 황경 통과 시각
    var back = mod(solarLongitude(jdUT) - startLon, 360) / 0.9856473;
    var prev = findSolarTermJD(jdUT - back, startLon);
    if (prev > jdUT) prev = findSolarTermJD(prev - 360 / 0.9856473, startLon);

    var fwd = mod(nextLon - solarLongitude(jdUT), 360) / 0.9856473;
    var next = findSolarTermJD(jdUT + fwd, nextLon);
    if (next < jdUT) next = findSolarTermJD(next + 360 / 0.9856473, nextLon);

    return {
      index: idx,
      term: MAJOR_TERMS[idx],
      nextTerm: MAJOR_TERMS[(idx + 1) % 12],
      startJD: prev,
      endJD: next
    };
  }

